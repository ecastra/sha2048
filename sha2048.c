/*********************** CPU FEATURE DETECTION ***********************/
// Safely check for CPU features at runtime.
static int has_avx512f_vl() {
#if defined(__GNUC__) || defined(__clang__)
    unsigned int eax, ebx, ecx, edx;
    if (!__get_cpuid(7, &eax, &ebx, &ecx, &edx)) return 0;
    // Check for AVX512F (bit 16 of EBX) and AVX512VL (bit 31 of EBX)
    return (ebx & (1 << 16)) && (ebx & (1 << 31));
#elif defined(_MSC_VER) && !defined(__clang__)
    int cpuInfo[4];
    __cpuidex(cpuInfo, 7, 0);
    return (cpuInfo[1] & (1 << 16)) && (cpuInfo[1] & (1 << 31));
#else
    return 0; // No SIMD support on unknown compilers
#endif
}

static int has_avx2() {
#if defined(__GNUC__) || defined(__clang__)
    unsigned int eax, ebx, ecx, edx;
    if (!__get_cpuid(7, &eax, &ebx, &ecx, &edx)) return 0;
    return (ebx & (1 << 5)); // Check for AVX2 (bit 5 of EBX)
#elif defined(_MSC_VER) && !defined(__clang__)
    int cpuInfo[4];
    __cpuidex(cpuInfo, 7, 0);
    return (cpuInfo[1] & (1 << 5));
#else
    return 0;
#endif
}


